import { describe, expect, it } from "vitest";
import { calculatePickupAvailability, localTimeCandidates, pickupScheduleInputSchema, pickupScheduleSnapshot, validatePickupSelection } from "../pickupScheduling";

const schedule = pickupScheduleInputSchema.parse({
  timeZone: "America/Los_Angeles",
  weeklyHours: [
    { dayOfWeek: 1, intervals: [{ open: "09:00", close: "17:00" }] },
    { dayOfWeek: 6, intervals: [{ open: "22:00", close: "02:00" }] },
  ],
  exceptions: [], slotMinutes: 30, maxAdvanceDays: 14, version: 1,
});

describe("pickup scheduling", () => {
  it("rejects ambiguous all-day intervals and invalid exception dates", () => {
    expect(pickupScheduleInputSchema.safeParse({ ...schedule, weeklyHours: [{ dayOfWeek: 1, intervals: [{ open: "09:00", close: "09:00" }] }] }).success).toBe(false);
    expect(pickupScheduleInputSchema.safeParse({ ...schedule, exceptions: [{ date: "2026-02-30", closed: true }] }).success).toBe(false);
  });

  it("offers immediate pickup only while open and server-generated future slots while closed", () => {
    const open = calculatePickupAvailability(schedule, new Date("2026-11-02T18:00:00.000Z"));
    expect(open.immediateAvailable).toBe(true);
    const closed = calculatePickupAvailability(schedule, new Date("2026-11-03T02:00:00.000Z"));
    expect(closed.immediateAvailable).toBe(false);
    expect(closed.slots.length).toBeGreaterThan(0);
    expect(() => validatePickupSelection(schedule, null, new Date("2026-11-03T02:00:00.000Z"))).toThrow("PICKUP_TIME_REQUIRED");
    expect(validatePickupSelection(schedule, closed.slots[0].at, new Date("2026-11-03T02:00:00.000Z")).mode).toBe("scheduled");
  });

  it("replaces weekly hours with holiday closures", () => {
    const holiday = { ...schedule, exceptions: [{ date: "2026-11-02", closed: true as const, label: "Holiday" }] };
    const availability = calculatePickupAvailability(holiday, new Date("2026-11-02T18:00:00.000Z"));
    expect(availability.immediateAvailable).toBe(false);
    expect(availability.slots.some(slot => slot.at.startsWith("2026-11-02"))).toBe(false);
  });

  it("supports overnight periods", () => {
    const availability = calculatePickupAvailability(schedule, new Date("2026-11-01T07:30:00.000Z"));
    expect(availability.immediateAvailable).toBe(true);
  });

  it("skips nonexistent DST wall times and represents repeated times as distinct instants", () => {
    expect(localTimeCandidates("2026-03-08", "02:30", "America/Los_Angeles")).toHaveLength(0);
    expect(localTimeCandidates("2026-11-01", "01:30", "America/Los_Angeles")).toHaveLength(2);
  });

  it("rejects client-submitted times that were not generated by the current schedule", () => {
    expect(() => validatePickupSelection(schedule, "2026-11-02T03:00:00.000Z", new Date("2026-11-01T12:00:00.000Z"))).toThrow("PICKUP_TIME_UNAVAILABLE");
  });

  it("rechecks a quoted slot against edited hours before order creation", () => {
    const now = new Date("2026-11-03T02:00:00.000Z");
    const quoted = calculatePickupAvailability(schedule, now).slots[0].at;
    const edited = { ...schedule, weeklyHours: [], version: schedule.version + 1 };
    expect(() => validatePickupSelection(edited, quoted, now)).toThrow("PICKUP_TIME_UNAVAILABLE");
  });

  it("uses each location's time zone rather than the browser or server zone", () => {
    const instant = new Date("2026-11-02T18:00:00.000Z");
    const losAngeles = calculatePickupAvailability(schedule, instant);
    const newYork = calculatePickupAvailability({ ...schedule, timeZone: "America/New_York" }, instant);
    expect(losAngeles.immediateAvailable).toBe(true); // 10:00 local
    expect(newYork.immediateAvailable).toBe(true); // 13:00 local

    const nearClose = new Date("2026-11-02T23:00:00.000Z");
    expect(calculatePickupAvailability(schedule, nearClose).immediateAvailable).toBe(true); // 15:00 local
    expect(calculatePickupAvailability({ ...schedule, timeZone: "America/New_York" }, nearClose).immediateAvailable).toBe(false); // 18:00 local
  });

  it("explains when no upcoming slots exist in the configured horizon", () => {
    const unavailable = calculatePickupAvailability({ ...schedule, weeklyHours: [], maxAdvanceDays: 1 }, new Date("2026-11-03T02:00:00.000Z"));
    expect(unavailable.immediateAvailable).toBe(false);
    expect(unavailable.slots).toEqual([]);
    expect(unavailable.message).toContain("no pickup times");
  });

  it("snapshots the selected schedule so later edits cannot alter an order", () => {
    const current = { ...schedule, weeklyHours: structuredClone(schedule.weeklyHours), updatedAt: new Date("2026-11-01T00:00:00.000Z") };
    const selection = validatePickupSelection(current, null, new Date("2026-11-02T18:00:00.000Z"));
    const snapshot = pickupScheduleSnapshot(current, { id: 7, name: "Storefront" }, selection);
    current.weeklyHours[0].intervals[0].open = "12:00";
    expect(snapshot.weeklyHours[0].intervals[0].open).toBe("09:00");
    expect(snapshot.timeZone).toBe("America/Los_Angeles");
  });
});
